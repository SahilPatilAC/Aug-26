class Grading{
	public static void main(String args[]){

		int marks=75;
	
		if(marks >= 80){
			System.out.println("Grade A");
		}
		else if(marks >= 65){
			System.out.println("Grade B");
		}
		else if(marks >= 45){
			System.out.println("Grade C");
		}		
		else{
			System.out.println("Fail");

		}
		
	}
}