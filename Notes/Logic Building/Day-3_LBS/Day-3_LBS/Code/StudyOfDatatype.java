class StudyOfDatatype{

		public static void main(String args[]){
		
		//byte
		byte age = 16;
		System.out.println(age);

		//int
		int salary = 50000;
		System.out.println(salary);

		//float
		float pie = 3.14f;
		System.out.println(pie);

		//short
		short distance = 10;
		System.out.println(distance);

		//long
		long mobile = 123957438L;
		System.out.println(mobile);

		//double
		double anualpackage = 1.64857;
		System.out.println(anualpackage);

		//char
		char section = 'A';
		System.out.println(section);
		
		//boolean
		boolean isPresent = true;
		System.out.println("Narayan" + isPresent);

	}
}